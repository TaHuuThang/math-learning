-- Giai đoạn 4: ngân hàng câu hỏi và hệ thống luyện tập.
-- Chỉ THÊM bảng/cột hoặc nới ràng buộc, không xóa dữ liệu cũ.

-- 1. Câu hỏi: trạng thái "chờ duyệt" (review) – câu có lỗi hoặc chưa xác minh không vào ngân hàng chính thức.
alter table questions drop constraint if exists questions_status_check;
alter table questions add constraint questions_status_check check (status in ('draft', 'review', 'published', 'archived'));
alter table questions
  add column quality_issues jsonb not null default '[]'::jsonb,   -- cảnh báo của bộ kiểm tra tự động
  add column verified_by uuid references users(id) on delete set null,
  add column verified_at timestamptz;
create index questions_status_idx on questions (textbook_id, status);

-- Giải thích cho từng phương án (trắc nghiệm) / từng nhận định (Đúng/Sai): gắn với phương án,
-- nên khi đảo thứ tự phương án lời giải không bị sai.
alter table answers add column explanation text;

-- 2. Ảnh: phân biệt mục đích để phân quyền xem (ảnh bài làm chỉ chủ bài và giáo viên xem được).
alter table images add column purpose text not null default 'content' check (purpose in ('content', 'question', 'response'));

-- 3. Phiên luyện tập / đề luyện tập do học sinh tạo.
create table practice_sessions (
  id integer generated by default as identity primary key,
  user_id uuid not null references users(id) on delete cascade,
  textbook_id integer not null references textbooks(id),
  kind text not null check (kind in ('lesson', 'topic', 'chapter', 'mixed', 'level', 'retry', 'chapter_test', 'challenge')),
  mode text not null check (mode in ('practice', 'exam')),
  title text not null check (char_length(title) between 1 and 200),
  config jsonb not null default '{}'::jsonb,
  question_ids integer[] not null,
  option_orders jsonb not null default '{}'::jsonb,       -- {"<id câu>": "CADB"}: thứ tự phương án gốc theo vị trí hiển thị
  flagged integer[] not null default '{}'::integer[],
  draft_answers jsonb not null default '{}'::jsonb,
  time_limit_minutes smallint check (time_limit_minutes between 1 and 240),
  status text not null default 'in_progress' check (status in ('in_progress', 'submitted')),
  started_at timestamptz not null default now(),
  deadline_at timestamptz,
  submitted_at timestamptz,
  duration_seconds integer,
  correct_count smallint,
  partial_count smallint,
  incorrect_count smallint,
  blank_count smallint,
  pending_count smallint,
  score numeric(7,3),
  max_score numeric(7,3)
);
create index practice_sessions_user_idx on practice_sessions (user_id, started_at desc);

alter table question_responses add column practice_session_id integer references practice_sessions(id) on delete cascade;
create index question_responses_session_idx on question_responses (practice_session_id) where practice_session_id is not null;
create index question_responses_user_q_idx on question_responses (user_id, question_id, created_at desc);

-- 4. Cấu hình đề tạo tự động của giáo viên và các mã đề sinh ra từ cấu hình.
create table exam_blueprints (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id),
  title text not null check (char_length(title) between 1 and 200),
  config jsonb not null,
  created_by uuid not null references users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table tests
  add column blueprint_id integer references exam_blueprints(id) on delete set null,
  add column variant_code text check (variant_code ~ '^[0-9A-Za-z]{1,10}$');
alter table test_questions add column option_order text check (option_order ~ '^[A-D]{4}$');
