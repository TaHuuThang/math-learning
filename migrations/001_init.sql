create table questions (
  id integer generated by default as identity primary key,
  exercise_type_id smallint not null references exercise_types(id),
  textbook_id integer not null references textbooks(id),
  lesson_id integer references lessons(id) on delete set null,
  topic_id integer references topics(id) on delete set null,
  level smallint not null default 1 check (level between 1 and 4),
  stem text not null check (char_length(stem) between 1 and 8000),
  settings jsonb not null default '{}'::jsonb,
  points numeric(5,2) not null default 1 check (points > 0),
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  source text,
  created_by uuid references users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index questions_lesson_idx on questions (lesson_id, status);
create index questions_recent_idx on questions (status, created_at desc);

-- Phương án (trắc nghiệm), ý (đúng/sai), đáp án chấp nhận (trả lời ngắn)
create table answers (
  id integer generated by default as identity primary key,
  question_id integer not null references questions(id) on delete cascade,
  label text not null,
  content text not null,
  is_correct boolean not null default false,
  sort_order smallint not null,
  unique (question_id, label)
);

create table solutions (
  id integer generated by default as identity primary key,
  question_id integer not null references questions(id) on delete cascade,
  kind text not null default 'full' check (kind in ('hint', 'full', 'rubric')),
  content text not null,
  sort_order smallint not null default 0,
  unique (question_id, kind)
);

-- Hình ảnh: ảnh tải lên (lưu trong CSDL) hoặc hình vẽ hình học (mô tả bằng văn bản → SVG)
create table images (
  id integer generated by default as identity primary key,
  kind text not null check (kind in ('upload', 'figure')),
  mime text check (mime in ('image/png', 'image/jpeg', 'image/webp')),
  data bytea,
  figure_source text,
  byte_size integer,
  alt text not null default '',
  created_by uuid references users(id) on delete set null,
  created_at timestamptz not null default now(),
  check ((kind = 'upload' and data is not null and mime is not null) or (kind = 'figure' and figure_source is not null))
);

create table question_images (
  question_id integer not null references questions(id) on delete cascade,
  image_id integer not null references images(id) on delete cascade,
  sort_order smallint not null default 0,
  primary key (question_id, image_id)
);

-- ============ KIỂM TRA ============
create table tests (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id),
  title text not null check (char_length(title) between 1 and 200),
  description text,
  duration_minutes smallint check (duration_minutes between 1 and 240),
  status text not null default 'draft' check (status in ('draft', 'published', 'closed')),
  show_answers boolean not null default true,
  max_attempts smallint not null default 1 check (max_attempts between 1 and 10),
  opens_at timestamptz,
  closes_at timestamptz,
  created_by uuid not null references users(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table test_questions (
  test_id integer not null references tests(id) on delete cascade,
  question_id integer not null references questions(id) on delete restrict,
  sort_order smallint not null,
  points numeric(5,2) not null check (points > 0),
  primary key (test_id, question_id)
);

create table test_assignments (
  test_id integer not null references tests(id) on delete cascade,
  class_id integer not null references classes(id) on delete cascade,
  primary key (test_id, class_id)
);

create table test_results (
  id integer generated by default as identity primary key,
  test_id integer not null references tests(id) on delete cascade,
  student_id uuid not null references users(id) on delete cascade,
  attempt_no smallint not null default 1,
  status text not null default 'in_progress' check (status in ('in_progress', 'submitted', 'graded')),
  draft_answers jsonb not null default '{}'::jsonb,
  started_at timestamptz not null default now(),
  deadline_at timestamptz,
  submitted_at timestamptz,
  score numeric(6,2),
  max_score numeric(6,2),
  pending_manual smallint not null default 0,
  unique (test_id, student_id, attempt_no)
);
create index test_results_student_idx on test_results (student_id);

-- ============ BÀI LÀM, TIẾN ĐỘ, THÀNH TÍCH ============
create table question_responses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references users(id) on delete cascade,
  question_id integer not null references questions(id) on delete cascade,
  test_result_id integer references test_results(id) on delete cascade,
  context text not null check (context in ('practice', 'test', 'challenge')),
  response jsonb not null,
  status text not null check (status in ('correct', 'partial', 'incorrect', 'pending')),
  score numeric(6,3),
  points_awarded numeric(6,2),
  feedback text,
  graded_by uuid references users(id) on delete set null,
  graded_at timestamptz,
  created_at timestamptz not null default now()
);
create index question_responses_user_idx on question_responses (user_id, created_at desc);
create index question_responses_question_idx on question_responses (question_id);
create unique index question_responses_test_once on question_responses (test_result_id, question_id) where test_result_id is not null;

create table learning_progress (
  user_id uuid not null references users(id) on delete cascade,
  lesson_id integer not null references lessons(id) on delete cascade,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  first_viewed_at timestamptz not null default now(),
  last_viewed_at timestamptz not null default now(),
  completed_at timestamptz,
  view_count integer not null default 1,
  primary key (user_id, lesson_id)
);
create index learning_progress_recent_idx on learning_progress (user_id, last_viewed_at desc);

create table xp_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references users(id) on delete cascade,
  amount integer not null,
  reason text not null,
  ref text,
  created_at timestamptz not null default now()
);
create index xp_events_user_idx on xp_events (user_id, created_at desc);
-- Mỗi sự kiện có mã tham chiếu chỉ được cộng điểm một lần (chống "cày" điểm)
create unique index xp_events_once on xp_events (user_id, reason, ref) where ref is not null;

create table achievements (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  description text not null,
  icon text not null,
  tier text not null default 'bronze' check (tier in ('bronze', 'silver', 'gold')),
  xp_reward integer not null default 0,
  sort_order smallint not null
);

create table user_achievements (
  user_id uuid not null references users(id) on delete cascade,
  achievement_id smallint not null references achievements(id) on delete cascade,
  earned_at timestamptz not null default now(),
  primary key (user_id, achievement_id)
);

-- Nhật ký thao tác quan trọng (tạo tài khoản, đổi quyền, khóa…)
create table audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references users(id) on delete set null,
  action text not null,
  target text,
  detail jsonb,
  created_at timestamptz not null default now()
);
