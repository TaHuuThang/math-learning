-- MATH LEARNING – lược đồ cơ sở dữ liệu ban đầu (PostgreSQL ≥ 13)
-- Thiết kế cho nhiều môn, nhiều khối lớp (6–9), nhiều bộ sách; Toán 8 KNTT chỉ là dữ liệu.

-- ============ NGƯỜI DÙNG & PHÂN QUYỀN ============
create table roles (
  id smallint primary key,
  code text not null unique check (code in ('admin', 'teacher', 'student')),
  name text not null
);
insert into roles (id, code, name) values
  (1, 'admin', 'Quản trị viên'),
  (2, 'teacher', 'Giáo viên'),
  (3, 'student', 'Học sinh');

create table users (
  id uuid primary key default gen_random_uuid(),
  username text not null check (username ~ '^[a-z0-9._-]{3,40}$'),
  email text,
  password_hash text not null,
  full_name text not null check (char_length(full_name) between 1 and 120),
  role_id smallint not null references roles(id),
  status text not null default 'active' check (status in ('active', 'locked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_login_at timestamptz
);
create unique index users_username_key on users (lower(username));
create unique index users_email_key on users (lower(email)) where email is not null;

create table sessions (
  id bigint generated always as identity primary key,
  user_id uuid not null references users(id) on delete cascade,
  token_hash text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  expires_at timestamptz not null,
  ip text,
  user_agent text
);
create index sessions_user_idx on sessions (user_id);

create table login_attempts (
  id bigint generated always as identity primary key,
  username text not null,
  ip text not null,
  success boolean not null,
  created_at timestamptz not null default now()
);
create index login_attempts_user_idx on login_attempts (lower(username), created_at desc);
create index login_attempts_ip_idx on login_attempts (ip, created_at desc);

-- ============ CHƯƠNG TRÌNH HỌC ============
create table subjects (
  id smallint generated by default as identity primary key,
  code text not null unique,
  name text not null
);

create table grades (
  id smallint generated by default as identity primary key,
  level smallint not null unique check (level between 1 and 12),
  name text not null,
  status text not null default 'coming_soon' check (status in ('active', 'coming_soon', 'hidden')),
  sort_order smallint not null default 0
);

-- Một "sách" = môn + khối + bộ sách (VD: Toán 8 – Kết nối tri thức với cuộc sống)
create table textbooks (
  id integer generated by default as identity primary key,
  subject_id smallint not null references subjects(id),
  grade_id smallint not null references grades(id),
  slug text not null unique check (slug ~ '^[a-z0-9-]+$'),
  title text not null,
  series text not null,
  series_code text not null,
  program text not null default 'GDPT 2018',
  description text,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  is_default boolean not null default false,
  created_at timestamptz not null default now(),
  unique (subject_id, grade_id, series_code)
);
create unique index textbooks_one_default on textbooks (subject_id, grade_id) where is_default;

create table semesters (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id) on delete cascade,
  number smallint not null check (number in (1, 2)),
  name text not null,
  unique (textbook_id, number)
);

create table chapters (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id) on delete cascade,
  semester_id integer not null references semesters(id),
  code text not null,
  title text not null,
  description text,
  kind text not null default 'chapter' check (kind in ('chapter', 'activity')),
  sort_order smallint not null,
  unique (textbook_id, code)
);
create index chapters_textbook_idx on chapters (textbook_id, sort_order);

create table lessons (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id) on delete cascade,
  chapter_id integer not null references chapters(id) on delete cascade,
  number smallint,
  slug text not null check (slug ~ '^[a-z0-9-]+$'),
  title text not null,
  kind text not null default 'lesson' check (kind in ('lesson', 'practice', 'review', 'activity')),
  summary text,
  periods smallint check (periods between 0 and 20),
  estimated_minutes smallint check (estimated_minutes between 0 and 600),
  status text not null default 'draft' check (status in ('draft', 'published')),
  sort_order smallint not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references users(id) on delete set null,
  unique (textbook_id, slug)
);
create index lessons_chapter_idx on lessons (chapter_id, sort_order);

-- Nội dung bài học: mục tiêu, kiến thức, công thức, ví dụ, ghi chú (văn bản + công thức \( \) \[ \])
create table lesson_sections (
  id integer generated by default as identity primary key,
  lesson_id integer not null references lessons(id) on delete cascade,
  kind text not null check (kind in ('objective', 'knowledge', 'formula', 'example', 'note')),
  title text,
  body text not null,
  solution text,
  sort_order smallint not null
);
create index lesson_sections_lesson_idx on lesson_sections (lesson_id, sort_order);

-- Chủ đề / dạng toán trong bài
create table topics (
  id integer generated by default as identity primary key,
  lesson_id integer not null references lessons(id) on delete cascade,
  title text not null,
  method text,
  sort_order smallint not null
);
create index topics_lesson_idx on topics (lesson_id, sort_order);

-- Phân phối chương trình (theo năm học)
create table teaching_plans (
  id integer generated by default as identity primary key,
  textbook_id integer not null references textbooks(id) on delete cascade,
  school_year text not null,
  title text not null,
  created_at timestamptz not null default now(),
  unique (textbook_id, school_year)
);

create table teaching_plan_items (
  id integer generated by default as identity primary key,
  plan_id integer not null references teaching_plans(id) on delete cascade,
  position smallint not null,
  title text not null,
  lesson_id integer references lessons(id) on delete set null,
  periods smallint not null,
  period_from smallint not null,
  period_to smallint not null,
  weeks text not null,
  equipment text,
  note text,
  unique (plan_id, position)
);

-- ============ HỌC SINH, GIÁO VIÊN, LỚP ============
create table teachers (
  user_id uuid primary key references users(id) on delete cascade,
  school text,
  phone text
);

create table students (
  user_id uuid primary key references users(id) on delete cascade,
  grade_id smallint not null references grades(id),
  school text,
  student_code text
);

create table classes (
  id integer generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 40),
  grade_id smallint not null references grades(id),
  textbook_id integer references textbooks(id),
  school_year text not null check (school_year ~ '^\d{4}-\d{4}$'),
  teacher_id uuid not null references users(id),
  join_code text not null unique,
  status text not null default 'active' check (status in ('active', 'archived')),
  created_at timestamptz not null default now()
);
create index classes_teacher_idx on classes (teacher_id);

create table class_members (
  class_id integer not null references classes(id) on delete cascade,
  student_id uuid not null references users(id) on delete cascade,
  joined_at timestamptz not null default now(),
  primary key (class_id, student_id)
);
create index class_members_student_idx on class_members (student_id);

